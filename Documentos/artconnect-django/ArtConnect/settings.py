# Database
# https://docs.djangoproject.com/en/6.1/ref/settings/#databases

def banco_do_render(url):
    """Converte a DATABASE_URL do Render (postgresql://...) no formato do Django."""
    partes = urlparse(url)
    return {
        "ENGINE": "django.db.backends.postgresql",
        "NAME": partes.path.lstrip("/"),
        "USER": unquote(partes.username or ""),
        "PASSWORD": unquote(partes.password or ""),
        "HOST": partes.hostname or "",
        "PORT": str(partes.port or ""),
    }


# No computador usa SQLite (como nos exemplos da disciplina).
# No Render usa o PostgreSQL indicado na variável DATABASE_URL.
if os.environ.get("DATABASE_URL"):
    DATABASES = {"default": banco_do_render(os.environ["DATABASE_URL"])}
else:
    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.sqlite3",
            "NAME": BASE_DIR / "db.sqlite3",
        }
    }


